// Builds database/seed.sql — the SQL edition of the demo data — from the same catalogue the
// MongoDB seed uses (server/seed-catalog.js), so the two never drift apart.
//
//   node database/export-sql.js          (or: npm --prefix server run db:sql)
//
// server/test/sql.test.js fails when seed.sql is out of date with the catalogue.
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const { catalogBooks, editorialReviews } = require(path.join(__dirname, '..', 'server', 'seed-catalog.js'));

const seedFile = path.join(__dirname, 'seed.sql');

// Stable 24-hex ids (the same shape as a MongoDB ObjectId), so re-running the seed matches existing rows.
const idFor = (kind, key) => crypto.createHash('sha1').update(`booka-ru/${kind}/${key}`).digest('hex').slice(0, 24);

const sql = value => {
    if (value === null || value === undefined) return 'NULL';
    if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
    if (typeof value === 'number') return String(value);
    if (value instanceof Date) return `'${value.toISOString()}'`;
    return `'${String(value).replace(/'/g, "''")}'`;
};

function insert(table, rows) {
    const columns = Object.keys(rows[0]);
    const values = rows.map(row => `    (${columns.map(column => sql(row[column])).join(', ')})`);
    return `INSERT INTO ${table} (${columns.join(', ')}) VALUES\n${values.join(',\n')}\nON CONFLICT DO NOTHING;\n`;
}

const demoTime = new Date('2025-01-05T10:00:00.000Z');
const later = seconds => new Date(demoTime.getTime() + seconds * 1000);

// Demo accounts mirror server/seed-demo-accounts.js. They are LOCKED: '!' is not a valid
// scrypt "salt:hash", so nobody can sign in with them. Sign-in demo accounts are created by
// `npm --prefix server run db:seed` with passwords from DEMO_*_PASSWORD environment variables.
const LOCKED = '!';
const admin = { id: idFor('user', 'admin'), email: 'admin@example.com', name: 'Booka-Ru Test Admin', role: 'admin', permissions: ['*'] };
const staff = { id: idFor('user', 'staff'), email: 'bookaru.staff.test@example.com', name: 'Booka-Ru Test Staff', role: 'staff', permissions: ['books:write', 'orders:manage', 'support:handle', 'reviews:moderate'] };
const customer = { id: idFor('user', 'customer'), email: 'bookaru.customer.test@example.com', name: 'Booka-Ru Test Customer', role: 'customer', permissions: [] };
const accounts = [admin, staff, customer];

const books = catalogBooks.map(book => ({
    id: idFor('book', book.seedKey), seed_key: book.seedKey, isbn: book.isbn || null, name: book.name, author: book.author || null,
    description: book.description || null, image_url: book.imageURL || null, category: book.category || null, genre: book.genre || null,
    language: book.language || null, price: book.price, quantity: book.quantity, active: book.active !== false, created_at: book.createdAt
}));

const hobbit = books.find(book => book.seed_key === 'isbn-9780547928227');
const orderId = idFor('order', 'demo-order-1');

function buildSeedSql() {
    const parts = [
        `-- Booka-Ru demo data (SQL edition). Load after database/schema.sql:
--
--   PostgreSQL:  psql -d bookaru -f database/schema.sql -f database/seed.sql
--   SQLite:      sqlite3 bookaru.db < database/seed.sql
--
-- GENERATED by database/export-sql.js from server/seed-catalog.js. Do not edit by hand;
-- run \`npm --prefix server run db:sql\` after changing the catalogue.
--
-- Contents: ${books.length} books (English, Bangla and themed shelves), ${editorialReviews.length} approved editorial
-- reviews, 3 demo accounts (admin, staff, customer), a sample order with a two-message
-- support conversation, a pending customer review and an inactive welcome pop-up.
--
-- The demo accounts are LOCKED (password_hash '!'), so this file contains no credentials.
-- The live MongoDB application gets sign-in demo accounts from \`npm --prefix server run db:seed\`,
-- which reads the passwords from DEMO_*_PASSWORD environment variables.
--
-- Idempotent: rows have fixed ids and use ON CONFLICT DO NOTHING, so running it again is safe.
`,
        'BEGIN;\n',
        '-- Accounts',
        insert('users', accounts.map(user => ({ id: user.id, email: user.email, name: user.name, password_hash: LOCKED, role: user.role, active: true, created_at: demoTime, updated_at: demoTime }))),
        insert('user_permissions', accounts.flatMap(user => user.permissions.map(permission => ({ user_id: user.id, permission })))),
        `-- Catalogue: ${books.length} books`,
        insert('books', books),
        '-- Approved editorial reviews shown on the home page',
        insert('reviews', editorialReviews.map(review => ({
            id: idFor('review', review.seedKey), seed_key: review.seedKey, user_id: null, name: review.name, email: null, rating: review.rating,
            text: review.text, approved: review.approved, editorial: review.editorial, created_at: review.createdAt
        }))),
        '-- A customer review waiting for moderation',
        insert('reviews', [{
            id: idFor('review', 'demo-customer-review'), seed_key: 'demo-customer-review', user_id: customer.id, name: customer.name, email: customer.email, rating: 5,
            text: 'Fast delivery and the book arrived in perfect condition.', approved: false, editorial: false, created_at: later(120)
        }]),
        '-- Welcome pop-up (inactive until an admin switches it on)',
        insert('popups', [{
            id: idFor('popup', 'demo-welcome-popup'), seed_key: 'demo-welcome-popup', title: 'Welcome to Booka-Ru', image_url: '/fairytale-books.svg', link_url: '/',
            active: false, starts_at: null, ends_at: null, created_at: demoTime, updated_at: demoTime
        }]),
        '-- Sample order with a support conversation',
        insert('orders', [{
            id: orderId, seed_key: 'demo-order-1', user_id: customer.id, email: customer.email, customer_name: customer.name, book_id: hobbit.id,
            name: hobbit.name, image_url: hobbit.image_url, quantity: 1, price: hobbit.price, total: hobbit.price, status: 'confirmed',
            support_staff_id: null, support_staff_email: null, support_staff_name: null,
            shipping_address: 'House 12, Road 5, Dhanmondi, Dhaka 1205', notes: '', created_at: demoTime, updated_at: later(60)
        }]),
        insert('order_messages', [
            { id: idFor('message', 'demo-message-1'), seed_key: 'demo-message-1', order_id: orderId, sender_id: customer.id, sender_name: customer.name, sender_role: 'customer', text: 'Hi! When will my copy of The Hobbit arrive?', created_at: later(30) },
            { id: idFor('message', 'demo-message-2'), seed_key: 'demo-message-2', order_id: orderId, sender_id: admin.id, sender_name: admin.name, sender_role: 'admin', text: 'Your order is confirmed and will ship within two working days.', created_at: later(60) }
        ]),
        'COMMIT;\n'
    ];
    return parts.join('\n');
}

module.exports = { buildSeedSql, seedFile };

if (require.main === module) {
    fs.writeFileSync(seedFile, buildSeedSql());
    console.log(`Wrote ${path.relative(process.cwd(), seedFile)} (${books.length} books, ${editorialReviews.length + 1} reviews, ${accounts.length} accounts).`);
}
